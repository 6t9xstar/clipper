"""Caption groups -> an ASS subtitle script for libass (burned in by FFmpeg's `ass` filter).

Every line is its own event placed with \\pos at the same centre the browser preview uses
(clipper.edit.captions.line_centres), so line breaks, spacing and scaling are decided once, on the server.
The spoken-word highlight is done by splitting a group into time slices, one per word.
Pure functions; unit-tested in tests/test_render.py.
"""

from __future__ import annotations

import itertools
from collections.abc import Sequence
from typing import Any

from clipper.edit.captions import FRAME_H, FRAME_W, Preset, line_centres, line_text
from clipper.render import fontinfo


def colour(c: str) -> str:
    """#RRGGBB[AA] -> ASS &HAABBGGRR (ASS alpha is inverted: 00 = opaque)."""
    h = c.lstrip("#")
    if len(h) not in (6, 8):
        raise ValueError(f"bad colour {c!r}")
    r, g, b = h[0:2], h[2:4], h[4:6]
    a = 255 - int(h[6:8], 16) if len(h) == 8 else 0
    return f"&H{a:02X}{b}{g}{r}".upper()


def _inline(c: str) -> str:
    """Override-tag colour: &HBBGGRR& (no alpha)."""
    return colour(c)[:2] + colour(c)[4:] + "&"


def escape(text: str) -> str:
    """Text is never interpreted as ASS markup: braces start override blocks, backslash starts \\N etc."""
    return (
        text.replace("\\", "⧵")  # reverse solidus operator: looks like a backslash, never an escape  # noqa: RUF001
        .replace("{", "｛")  # noqa: RUF001 - fullwidth braces
        .replace("}", "｝")  # noqa: RUF001
        .replace("\n", " ")
    )


def _ts(t: float) -> str:
    cs = max(0, round(t * 100))
    h, cs = divmod(cs, 360000)
    m, cs = divmod(cs, 6000)
    s, cs = divmod(cs, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def baseline_offset(p: Preset) -> float:
    """px to add to a browser line centre so libass puts the baseline where the browser does.

    Browser: content area (hhea/typo ascent+descent) is centred in the line box. libass \\an5: the
    winAscent+winDescent box is centred on the \\pos point. Both measured in tests/test_render.py."""
    f = p.font
    em = p.size / f.units_per_em
    browser = (f.typo_ascent - f.typo_descent) / 2 * em  # typo_descent is positive here
    libass = (f.win_ascent - f.win_descent) / 2 * em
    return browser - libass


def build(groups: Sequence[dict[str, Any]], p: Preset, position: float | None, duration: float) -> str:
    f = p.font
    ass_size = p.size / f.css_scale
    box = p.box is not None

    def style(
        name: str, primary: str, border_style: int, outline: int, outline_colour: str, shadow: int
    ) -> str:
        fields = (
            name,
            f.family,
            f"{ass_size:.2f}",
            primary,
            colour(p.highlight or p.color),
            outline_colour,
            "&H33000000",  # shadow: black at 80 %
            -1 if f.bold else 0,
            0,
            0,
            0,
            100,
            100,
            0,
            0,
            border_style,
            outline,
            shadow,
            5,
            0,
            0,
            0,
            1,
        )
        return "Style: " + ",".join(str(x) for x in fields)

    styles = [
        style(
            "Caption",
            colour(p.color),
            1,
            0 if box else p.outline,
            colour(p.outline_color),
            0 if box else p.shadow,
        ),
    ]
    if p.box is not None:
        # One box per line, drawn from an invisible un-highlighted copy of the line on a lower layer. Colour
        # changes inside a line would otherwise make libass draw one (overlapping) box per colour run.
        styles.append(style("Box", "&HFF000000", 3, p.box_padding, colour(p.box), 0))
    out = [
        "[Script Info]",
        "; generated by Clipper",
        "ScriptType: v4.00+",
        f"PlayResX: {FRAME_W}",
        f"PlayResY: {FRAME_H}",
        "ScaledBorderAndShadow: yes",
        "WrapStyle: 2",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, "
        "Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
        "Alignment, MarginL, MarginR, MarginV, Encoding",
        *styles,
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    shift = baseline_offset(p)
    hl = _inline(p.highlight) if p.highlight else None
    base = _inline(p.color)

    def place(y: float, fit: float) -> str:
        scale = f"\\fscx{fit * 100:.2f}\\fscy{fit * 100:.2f}" if fit < 1 else ""
        return f"{{\\an5\\pos({FRAME_W / 2:.0f},{y + shift * fit:.1f}){scale}}}"

    for g in groups:
        lines = g["lines"]
        fits = g.get("fit") or [1.0] * len(lines)
        ys = line_centres(len(lines), p, position)
        end = min(g["e"], duration)
        if box:
            for ln, y, fit in zip(lines, ys, fits, strict=True):
                text = escape(line_text(ln, p))
                out.append(f"Dialogue: 0,{_ts(g['s'])},{_ts(end)},Box,,0,0,0,,{place(y, fit)}{text}")
        # time slices: the highlight changes at every word boundary inside the group
        cuts = sorted({g["s"], g["e"], *(w[k] for ln in lines for w in ln for k in ("s", "e"))})
        cuts = [c for c in cuts if g["s"] <= c <= end]
        slices = list(itertools.pairwise(cuts)) if hl else [(g["s"], end)]
        for a, b in slices:
            if b - a < 0.005:
                continue
            for ln, y, fit in zip(lines, ys, fits, strict=True):
                words = []
                for w in ln:
                    t = escape(line_text([w], p))
                    words.append(f"{{\\1c{hl}}}{t}{{\\1c{base}}}" if hl and w["s"] <= a < w["e"] else t)
                out.append(f"Dialogue: 1,{_ts(a)},{_ts(b)},Caption,,0,0,0,,{place(y, fit)}" + " ".join(words))
    return "\n".join(out) + "\n"


def fonts_dir() -> str:
    return str(fontinfo.FONTS_DIR)
